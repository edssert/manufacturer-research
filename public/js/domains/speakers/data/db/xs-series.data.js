const AMP_IDS = {
  "10D": "amp-db-10d",
  "30D": "amp-db-30d",
  "40D": "amp-db-40d",
  D80: "amp-db-d80",
};

function amplifierRows(models, perCh) {
  return models.map(model => ({
    model,
    configs: [{ mode: "Standard", perCh, total: perCh * 4 }],
  }));
}

function makePoint(spec) {
  const ampModels = spec.ampModels || ["10D", "30D", "D80", "40D"];
  return {
    id: `spk-db-${spec.name.toLowerCase()}`,
    mfr: "d&b audiotechnik",
    mk: "db",
    name: spec.name,
    series: "xS Series",
    throwCat: null,
    type: "Point",
    throw: null,
    lowInch: spec.lowInch,
    lowQty: spec.lowQty,
    crossover: "2-way, passive",
    crossoverTags: ["2-way", "passive"],
    spl: spec.spl,
    cov: { h: spec.h, v: spec.v, ...(spec.rotatable ? { rotatable: true } : {}) },
    freqs: [{ db: "-5 dB", lo: spec.freq[0], hi: spec.freq[1] }],
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: null,
    ip: null,
    dims: spec.dims,
    amps: amplifierRows(ampModels, spec.perCh),
    ampRaw: `${ampModels.join("/")} (${spec.perCh} cabinets/channel)`,
    notes:
      "Passive installation point source; maximum SPL uses the highest output stated in the official system table.",
    img: spec.img,
    relations: { ampIds: ampModels.map(model => AMP_IDS[model]).filter(Boolean) },
    watt: spec.watt,
    mechanicalSafety: null,
    presets: null,
    cardioidCapability: "No",
  };
}

function makeSub(spec) {
  const ampModels = spec.ampModels || ["10D", "30D", "D80", "40D"];
  return {
    id: `spk-db-${spec.name.toLowerCase()}`,
    mfr: "d&b audiotechnik",
    mk: "db",
    name: spec.name,
    series: "xS Series",
    throwCat: null,
    type: "Subwoofer",
    throw: null,
    lowInch: spec.lowInch,
    lowQty: spec.lowQty,
    crossover: "Subwoofer, passive",
    crossoverTags: ["passive"],
    spl: spec.spl,
    cov: null,
    freqs: spec.freqs,
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: null,
    ip: null,
    dims: spec.dims,
    amps: amplifierRows(ampModels, spec.perCh),
    ampRaw: `${ampModels.join("/")} (${spec.perCh} cabinets/channel)`,
    notes: spec.cardioid
      ? "Passive cardioid installation subwoofer."
      : "Passive omnidirectional installation subwoofer.",
    img: spec.img,
    relations: { ampIds: ampModels.map(model => AMP_IDS[model]).filter(Boolean) },
    watt: spec.watt,
    mechanicalSafety: null,
    presets: null,
    cardioidCapability: spec.cardioid ? "Integrated" : "No",
  };
}

