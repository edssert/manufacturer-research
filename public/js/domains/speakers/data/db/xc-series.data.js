const AMP_MODELS = ["10D", "5D", "30D", "D80", "40D"];
const AMP_IDS = {
  "10D": "amp-db-10d",
  "5D": "amp-db-5d",
  "30D": "amp-db-30d",
  "40D": "amp-db-40d",
  D80: "amp-db-d80",
};

function makeColumn(spec) {
  return {
    id: `spk-db-${spec.name.toLowerCase()}`,
    mfr: "d&b audiotechnik",
    mk: "db",
    name: spec.name,
    series: "xC Series",
    throwCat: null,
    type: "Colinear",
    throw: null,
    lowInch: 4,
    lowQty: spec.lowQty,
    crossover: "2-way, passive",
    crossoverTags: ["2-way", "passive"],
    spl: spec.spl,
    cov: { h: "90°", v: spec.v },
    freqs: [{ db: "-5 dB", lo: "110 Hz", hi: spec.highFrequency }],
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: null,
    ip: null,
    dims: spec.dims,
    amps: AMP_MODELS.map(model => ({
      model,
      configs: [{ mode: "Standard", perCh: spec.perCh, total: spec.perCh * 4 }],
    })),
    ampRaw: `${AMP_MODELS.join("/")} (${spec.perCh} cabinets/channel)`,
    notes: spec.notes,
    img: spec.img,
    relations: { ampIds: AMP_MODELS.map(model => AMP_IDS[model]) },
    watt: spec.watt,
    mechanicalSafety: null,
    presets: null,
    cardioidCapability: "Integrated",
  };
}

