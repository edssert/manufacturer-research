function makeETop(name, img) {
  const spec = E_SPECS[name];
  return {
    id: `spk-db-${name.toLowerCase()}`,
    mfr: "d&b audiotechnik",
    mk: "db",
    name,
    series: "E Series",
    throwCat: null,
    type: "Point",
    throw: "Multipurpose point source",
    lowInch: spec.lowInch,
    lowQty: 1,
    crossover: "2-way, passive",
    crossoverTags: ["2-way", "passive"],
    spl: spec.spl,
    cov: { h: spec.h, v: spec.v, rotatable: name !== "E4" && name !== "E5" },
    freqs: [{ db: "-5 dB", lo: spec.lo, hi: spec.hi }],
    weight: spec.weight,
    transducers: `LF: 1 × ${spec.lowInch}″ · HF: 1 × ${spec.hf}″ coaxial`,
    connectors: null,
    ip: null,
    dims: spec.dims,
    amps: [],
    ampRaw: "10D, 30D, D80/40D",
    notes: "Passive coaxial E-Series point source.",
    img,
    relations: { ampIds: [] },
    watt: spec.watt,
    mechanicalSafety: null,
    presets: null,
    cardioidCapability: "No",
  };
}

