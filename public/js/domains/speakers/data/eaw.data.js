function makeEaw(spec) {
  const operating = spec.operatingMode || (spec.type === "Subwoofer" ? "Subwoofer" : "Unknown operating mode");
  const mode = spec.selfPowered ? "active" : /passive/i.test(operating) ? "passive" : "externally powered";
  return {
    id: `spk-eaw-${spec.slug}`,
    mfr: "EAW",
    mk: "eaw",
    name: spec.name,
    series: spec.series,
    throwCat: null,
    type: spec.type,
    throw: spec.type === "Line Array" ? "Line array" : spec.type === "Point" ? "Point source" : null,
    lowInch: spec.lowInch,
    lowQty: spec.lowQty,
    crossover: operating,
    crossoverTags: [mode],
    spl: spec.spl,
    cov: { h: spec.h, v: spec.v },
    freqs: spec.range[0] && spec.range[1] ? [{ db: "Published range", lo: spec.range[0], hi: spec.range[1] }] : [],
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: spec.connections,
    ip: null,
    dims: spec.dims,
    amps: [],
    selfPowered: spec.selfPowered,
    ampRaw: operating,
    img: spec.img,
    views: spec.img ? [{ label: "Official", src: spec.img }] : [],
    relations: { ampIds: [] },
    watt: null,
    cardioidCapability: null,
    notes: `${spec.status === "pending" ? "Pending exact-model common card facts; unknown values remain null. " : ""}Official EAW product page, accessed 2026-08-18: ${spec.sourcePage}`,
  };
}

