function makeUp(name, img) {
  const spec = UP_SPECS[name];
  return {
    id: `spk-my-${name.toLowerCase()}`,
    mfr: "Meyer Sound",
    mk: "my",
    name,
    cardioidCapability: "No",
    series: "UP Series",
    throwCat: null,
    type: "Point",
    throw: "Point source",
    lowInch: spec.lowInch,
    lowQty: spec.lowQty,
    crossover: "2-way, active",
    crossoverTags: ["2-way", "active"],
    spl: spec.spl,
    cov: { h: spec.h, v: spec.v },
    freqs: spec.freqs,
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: spec.connectors,
    ip: spec.ip ?? null,
    dims: spec.dims,
    amps: [],
    selfPowered: true,
    ampRaw: null,
    img,
    relations: { ampIds: [] },
    watt: spec.watt,
    wattByBand: null,
    notes: `Self-powered 2-way point source. ${spec.powerNote} Card SPL uses the published ${spec.publishedSpl} Linear Peak SPL (M-noise), measured free-field at 4 m and referred to 1 m at the onset of limiting; fractional values are rounded down to avoid overstatement.`,
  };
}

