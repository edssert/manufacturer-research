function makeUltraX(name, img) {
  const spec = ULTRA_X[name];
  const compact = spec.lowInch === 5;
  const highInch = compact ? 2 : spec.lowInch === 8 ? 3 : 4;
  return {
    id: `spk-my-${name.toLowerCase()}`,
    mfr: "Meyer Sound",
    mk: "my",
    name,
    series: "ULTRA-X Series",
    throwCat: null,
    type: "Point",
    throw: "Point source",
    lowInch: spec.lowInch,
    lowQty: 2,
    crossover: "2-way, active",
    crossoverTags: ["2-way", "active"],
    spl: spec.spl,
    cov: { h: spec.h, v: spec.v, rotatable: name !== "ULTRA-X23" && name !== "ULTRA-X23XP" },
    freqs: [{ db: name.startsWith("ULTRA-X8") ? "±6 dB" : "Operating range", lo: spec.lo, hi: spec.hi }],
    weight: spec.weight,
    transducers: `LF: 2 × ${spec.lowInch}″ · HF: 1 × ${highInch}″`,
    connectors: spec.dc
      ? "Phoenix 5-pin balanced audio + 48 V DC from Meyer Sound MPS"
      : name.startsWith("ULTRA-X8")
        ? "XLR 3-pin TOP analog; etherCON TOP Milan; powerCON TRUE1 TOP"
        : "XLR 3-pin analog (5-pin RMS optional); Milan version available; AC powerCON",
    ip: name.startsWith("ULTRA-X8") ? "IP55 (OT version)" : "IP54 (weather-protected version)",
    dims: spec.dims,
    amps: [],
    selfPowered: true,
    ampRaw: null,
    notes: name.startsWith("ULTRA-X8")
      ? "AES75 peak level is used for card comparison; the datasheet also records RMS and A-weighted levels."
      : name.startsWith("ULTRA-X4")
        ? "Manufacturer Maximum SPL is used for card comparison; Linear Peak SPL remains documented in the canonical source."
        : "Linear Peak SPL uses the highest published Meyer noise measurement, rounded down where fractional to avoid overstatement.",
    img,
    relations: { ampIds: [] },
    watt: spec.watt,
    mechanicalSafety: null,
    presets: null,
    cardioidCapability: "No",
  };
}

