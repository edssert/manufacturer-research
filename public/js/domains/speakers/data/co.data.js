const COHESION_SERIES_ORDER = ["CO Series", "CP Series", "CM Series", "CSB Series", "CF Series"];

function makeCohesion(spec) {
  const slug = spec.slug ?? spec.name.toLowerCase();
  const active = spec.crossover.includes("active");
  const passive = spec.crossover.includes("passive");
  return {
    id: `spk-co-${slug}`,
    mfr: "Cohesion",
    mk: "co",
    name: spec.name,
    series: spec.series,
    throwCat: null,
    type: spec.type,
    throw: spec.type === "Line Array" ? "Variable-curvature line array" : null,
    lowInch: spec.lowInch,
    lowQty: spec.lowQty,
    crossover: spec.crossover,
    crossoverTags: spec.crossover.split(", "),
    spl: spec.spl,
    cov: { h: spec.h ?? null, v: spec.v ?? null, ...(spec.rotatable ? { rotatable: true } : {}) },
    freqs: [
      { db: "-10 dB", lo: spec.range[0], hi: spec.range[1] },
      { db: "±3 dB", lo: spec.response[0], hi: spec.response[1] },
    ],
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: spec.connectors,
    ip: null,
    dims: spec.dims,
    amps: [],
    selfPowered: spec.selfPowered ?? false,
    ampRaw: spec.selfPowered
      ? `Onboard amplification${spec.watt ? `, ${spec.watt} W` : ""}`
      : active
        ? "Cohesion amplification with Lake Controller and custom DSP settings; multiple amplifier channels required"
        : passive
          ? "Cohesion amplification with Lake Controller and custom DSP settings; single amplifier channel"
          : null,
    img: spec.img,
    views: [{ label: "Official", src: spec.img }],
    relations: { ampIds: [] },
    watt: spec.watt ?? null,
    cardioidCapability: spec.cardioidCapability ?? "No",
    notes: `${spec.notes ? `${spec.notes} ` : ""}Official Cohesion product page, accessed 2026-08-18.`,
  };
}

export const CO_SPEAKERS = [...COHESION_MODELS]
  .sort((a, b) => COHESION_SERIES_ORDER.indexOf(a.series) - COHESION_SERIES_ORDER.indexOf(b.series))
  .map(makeCohesion);
