const PK_SERIES_ORDER = ["Line Source", "Low Frequency", "Point Source"];

function makePkSound(spec) {
  const slug = spec.slug ?? spec.name.toLowerCase();
  return {
    id: `spk-pk-${slug}`,
    mfr: "PK Sound",
    mk: "pk",
    name: spec.name,
    series: spec.series,
    throwCat: null,
    type: spec.type,
    throw: spec.type === "Line Array" ? "Robotic line source" : null,
    lowInch: spec.lowInch,
    lowQty: spec.lowQty,
    crossover: spec.crossover,
    crossoverTags: spec.crossover.split(", "),
    spl: spec.spl,
    cov: { h: spec.h ?? null, v: spec.v ?? null },
    freqs: [{ db: "Frequency response", lo: spec.range[0], hi: spec.range[1] }],
    weight: spec.weight,
    transducers: spec.transducers,
    connectors: spec.connectors,
    ip: spec.ip,
    dims: spec.dims,
    amps: [],
    selfPowered: true,
    ampRaw: spec.amplifier,
    img: spec.img,
    views: [{ label: "Official", src: spec.img }],
    relations: { ampIds: [] },
    cardioidCapability: spec.cardioidCapability ?? "No",
    notes: `${spec.notes ? `${spec.notes} ` : ""}Official PK Sound product page, accessed 2026-08-18.`,
  };
}

export const PK_SPEAKERS = [...PK_MODELS]
  .sort((a, b) => PK_SERIES_ORDER.indexOf(a.series) - PK_SERIES_ORDER.indexOf(b.series))
  .map(makePkSound);
