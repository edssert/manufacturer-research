function makeAdamson(model) {
  const [
    name,
    series,
    type,
    lowInch,
    lowQty,
    way,
    spl,
    h,
    v,
    lo,
    hi,
    weight,
    transducers,
    dims,
    ampRaw,
    connectors,
    selfPowered,
  ] = model;
  const slug = name.toLowerCase();
  const active = selfPowered ? "active" : "passive";
  return {
    id: `spk-ad-${slug}`,
    mfr: "Adamson",
    mk: "ad",
    name,
    series,
    throwCat: null,
    type,
    throw: type === "Line Array" ? "Line source" : type === "Point" ? "Point source" : null,
    lowInch,
    lowQty,
    crossover: `${way}, ${active}`,
    crossoverTags: way === "Subwoofer" ? [active] : [way, active],
    spl,
    cov: h ? { h, v, rotatable: h.includes("/") || h.includes(" to ") } : null,
    freqs: [{ db: "±3 dB", lo, hi }],
    weight,
    transducers,
    connectors,
    ip: series === "IS Series" ? "Weatherized option with IP67 cable gland" : null,
    dims,
    amps: [],
    ampRaw,
    img: AD_IMAGE_PATHS[name],
    views: [{ label: "Official", src: AD_IMAGE_PATHS[name] }],
    ...(name === "VGx" || name === "VGt" ? { cardMediaFit: "cover" } : {}),
    relations: { ampIds: [] },
    watt: null,
    mechanicalSafety: null,
    presets: null,
    cardioidCapability: ["VGd", "VGo"].includes(name) ? "Dedicated cardioid" : "No",
    notes:
      name === "M10"
        ? "Official Adamson M10 technical data sheet values; the current product page has conflicting powered-MG10 fields."
        : "Official Adamson current product page specification, accessed 2026-08-18.",
    ...(selfPowered ? { selfPowered: true } : {}),
  };
}

export const AD_SPEAKERS = AD_MODELS.map(makeAdamson);
